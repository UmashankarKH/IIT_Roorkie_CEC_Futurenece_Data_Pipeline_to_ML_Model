"""Run the business-question SQL on both pipelines and dump evidence tables to docs/evidence.md."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "include"))
import nammamart_common as nc  # noqa: E402

con = nc.connect(read_only=True)
out = ["# Evidence (generated by scripts/export_evidence.py from the Airflow runs)\n"]


def table(title, sql, limit=None):
    df = con.execute(sql).fetchdf()
    if limit:
        df = df.head(limit)
    out.append(f"### {title}\n\n```sql\n{sql.strip()}\n```\n\n{df.to_markdown(index=False, floatfmt=".2f")}\n")


for tag, path in (("ETL", "business_questions_etl.sql"), ("ELT", "business_questions_elt.sql")):
    out.append(f"## Business questions - {tag}\n")
    text = (ROOT / "docs" / "sql" / path).read_text()
    for block in re.split(r"(?m)^-- (?=Q\d)", text)[1:]:
        title, _, sql = block.partition("\n")
        for i, stmt in enumerate([s for s in sql.split(";") if s.strip()]):
            table(f"{title}" + (f" ({i + 1})" if i else ""), stmt)

out.append("## Run audit and quality scorecard\n")
table("pipeline_runs (all runs)", "SELECT * FROM pipeline_runs ORDER BY end_time")
table("dq_results - latest ETL run, failing checks", """SELECT dimension, check_name, severity, rows_checked, rows_failed, status FROM dq_results
 WHERE dag_id = 'nammamart_etl_mohanrajs' AND run_id = (SELECT run_id FROM dq_results WHERE dag_id = 'nammamart_etl_mohanrajs' ORDER BY checked_at DESC LIMIT 1)
 AND rows_failed > 0 ORDER BY dimension, check_name""")
table("dq_results - latest ELT run, failing checks", """SELECT dimension, check_name, severity, rows_checked, rows_failed, status FROM dq_results
 WHERE dag_id = 'nammamart_elt_mohanrajs' AND run_id = (SELECT run_id FROM dq_results WHERE dag_id = 'nammamart_elt_mohanrajs' ORDER BY checked_at DESC LIMIT 1)
 AND rows_failed > 0 ORDER BY dimension, check_name""")
table("dq_results - checks per dimension per DAG (latest run)", """SELECT dag_id, dimension, count(*) AS checks, count(*) FILTER (WHERE severity = 'Critical') AS critical,
 sum(rows_failed) AS rows_failed FROM dq_results WHERE run_id IN (SELECT run_id FROM pipeline_runs ORDER BY end_time DESC LIMIT 2) GROUP BY 1, 2 ORDER BY 1, 2""")
(ROOT / "docs" / "evidence.md").write_text("\n".join(out), encoding="utf-8")
print("wrote docs/evidence.md")
